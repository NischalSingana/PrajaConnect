import * as React from "react"
import { cn } from "@/lib/utils"

const Card = React.forwardRef<
  HTMLDivElement,
  React.HTMLAttributes<HTMLDivElement> & { hoverable?: boolean; glass?: boolean }
>(({ className, hoverable, glass = true, ...props }, ref) => (
  <div
    ref={ref}
    className={cn(
      "rounded-[2rem] border border-[var(--border-color)] bg-[var(--surface-color)] text-[var(--text-color)] shadow-xl overflow-hidden",
      glass && "bg-glass backdrop-blur-xl border-white/5",
      hoverable && "transition-all duration-300 hover:shadow-[0_20px_50px_-12px_rgba(0,0,0,0.5)] hover:-translate-y-2 hover:border-[var(--color-primary-500)]/30 cursor-pointer",
      className
    )}
    {...props}
  />
))
Card.displayName = "Card"

